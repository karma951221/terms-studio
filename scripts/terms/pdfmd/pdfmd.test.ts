import { describe, expect, it } from "vitest";

import { parseTerms } from "../parse";
import { convertBody, convertUnit, fixtureName, readSourceMeta, splitUnits } from "./pdfmd";

/** 본문 조각만 바꿔 보는 도우미 — 조 하나짜리. */
const body = (...lines: string[]) => convertBody(["### 제1조(시험)", "", ...lines]);

describe("convertBody — PDF 추출 형식 → 파싱양식 본문", () => {
  it("관 · 조 · 항 · 호 · 목 마커를 바꾸고 번호 글자는 지운다", () => {
    const out = convertBody([
      "## 제1관 목적",
      "",
      "### 제1조(목적)",
      "",
      "[1] 첫 항입니다.",
      "",
      "① 첫 호",
      "",
      "1) 첫 목",
      "",
      "2) 둘째 목",
      "",
      "[2] 둘째 항입니다.",
      "",
      "### 제27조의1(보험료의 납입면제)",
      "",
      "단독 본문입니다.",
    ]);
    expect(out).toBe(
      [
        "# 제1관 목적",
        "",
        "## 제1조(목적)",
        "",
        "@ 첫 항입니다.",
        "",
        "  - 첫 호",
        "",
        "    - 첫 목",
        "",
        "    - 둘째 목",
        "",
        "@ 둘째 항입니다.",
        "",
        "## 제27조의1(보험료의 납입면제)",
        "",
        "= 단독 본문입니다.",
      ].join("\n"),
    );
  });

  it("조 제목 안의 괄호는 그대로 둔다", () => {
    expect(convertBody(["### 제30조(부활(효력회복))", "", "본문."])).toContain("## 제30조(부활(효력회복))");
  });

  it("항 번호 없는 머리말은 첫 항에 붙인다 — 항 번호가 밀리지 않게 (2604 제2조 관례)", () => {
    expect(body("다음과 같습니다.", "", "[1] 계약 관련 용어", "", "[2] 지급사유 관련 용어")).toBe(
      ["## 제1조(시험)", "", "@ 다음과 같습니다. 계약 관련 용어", "", "@ 지급사유 관련 용어"].join("\n"),
    );
  });

  it("쪽 주석은 지우고, 쪽 경계에서 끊긴 문장은 앞 줄에 잇는다", () => {
    expect(body("[1] 보험 가입 후 일정기간 내에 보험사고가", "", "<!-- p.107 -->", "발생할 경우 지급합니다.")).toBe(
      ["## 제1조(시험)", "", "@ 보험 가입 후 일정기간 내에 보험사고가 발생할 경우 지급합니다."].join("\n"),
    );
  });

  it("【 로 시작해 줄이 갈린 문장은 띄어쓰기 없이 잇는다", () => {
    expect(body("[1] 치료를 목적으로", "", "【별표3(수술분류표)】에서 정한 수술을 받은 경우 지급합니다.")).toBe(
      ["## 제1조(시험)", "", "@ 치료를 목적으로【별표3(수술분류표)】에서 정한 수술을 받은 경우 지급합니다."].join("\n"),
    );
  });

  it("> 인용 박스 → 용어풀이 블록 — 【제목】은 첫 줄, 번호 줄은 `- `, 이어지는 평문은 한 줄로", () => {
    expect(
      body(
        "[1] 본문입니다.",
        "",
        "> 【연단위 복리】 이자 계산방법을 말합니다.",
        "",
        "> 원금 100원을 가정할 때",
        "",
        "> - 1년 후 원리금 : 110원",
        "",
        "> 1\\. 의원급 의료기관",
        "",
        "> 【심신상실】 정신병 등",
      ),
    ).toBe(
      [
        "## 제1조(시험)",
        "",
        "@ 본문입니다.",
        "",
        "```용어풀이",
        "【연단위 복리】",
        "이자 계산방법을 말합니다. 원금 100원을 가정할 때",
        "- 1년 후 원리금 : 110원",
        "- 의원급 의료기관",
        "```",
        "",
        "```용어풀이",
        "【심신상실】",
        "정신병 등",
        "```",
      ].join("\n"),
    );
  });

  it("박스 한 줄에 몰린 글머리(` - ` · `·`)는 줄을 가른다 — 셈의 `-` 는 두고", () => {
    expect(body("본문.", "", "> 【부호】 사용됩니다. - 검표(+) : 원인 - 별표(*) : 발현")).toContain("【부호】\n사용됩니다.\n- 검표(+) : 원인\n- 별표(*) : 발현\n```");
    expect(body("본문.", "", "> · 화상진단비보장 · 화상수술비보장")).toContain("```용어풀이\n- 화상진단비보장\n- 화상수술비보장\n```");
    expect(body("본문.", "", "> 【나이】 2023년 4월 14일 - 1988년 10월 2일 = 34년")).toContain("【나이】\n2023년 4월 14일 - 1988년 10월 2일 = 34년\n```");
  });

  it("박스 안 문장도 쪽 경계를 넘어 잇는다", () => {
    expect(body("본문.", "", "> 【삭감】 보험사고가", "", "<!-- p.107 -->", "> 발생할 경우 감액합니다.")).toContain(
      "【삭감】\n보험사고가 발생할 경우 감액합니다.\n```",
    );
  });

  it("마크다운 표 → ```표 블록 (셀은 다듬고, 쪽 경계로 갈린 같은 머리 표는 합친다)", () => {
    expect(
      body("[1] 아래와 같습니다.", "", "| 구 분 | 지급금액 |", "|---|---|", "| 1종 | 가 |", "", "<!-- p.9 -->", "| 구 분 | 지급금액 |", "|---|---|", "| 2종 | 나 |"),
    ).toBe(
      ["## 제1조(시험)", "", "@ 아래와 같습니다.", "", "```표", "제목: (없음)", "|구 분|지급금액|", "|---|---|", "|1종|가|", "|2종|나|", "```"].join("\n"),
    );
  });

  it("【제목】 줄 아래의 그림 · 설명 · 표는 그 제목을 단다", () => {
    expect(
      body(
        "[1] 지급합니다.",
        "",
        "【보험금 지급예시(1)】",
        "",
        "[그림 — 원문 PDF p.122]",
        "",
        "※ 설명",
        "",
        "① : A수술 지급",
        "",
        "② : 미지급",
        "",
        "| 지급일 | 금액 |",
        "|---|---|",
        "| 4월 | 2천만원 |",
        "",
        "[2] 다음 항입니다.",
      ),
    ).toBe(
      [
        "## 제1조(시험)",
        "",
        "@ 지급합니다.",
        "",
        "```그림",
        "설명: 보험금 지급예시(1) — 원문 PDF p.122",
        "```",
        "",
        "```용어풀이",
        "【보험금 지급예시(1)】",
        "※ 설명",
        "① : A수술 지급",
        "② : 미지급",
        "```",
        "",
        "```표",
        "제목: 보험금 지급예시(1)",
        "|지급일|금액|",
        "|---|---|",
        "|4월|2천만원|",
        "```",
        "",
        "@ 다음 항입니다.",
      ].join("\n"),
    );
  });

  it("【제목】에 글이 붙은 줄(문장이 끝난 뒤)은 그 제목의 박스", () => {
    expect(body("[1] 지급합니다.", "", "【암보장개시일 [예시]】 (단, 15세 이상)계약일 90일")).toContain(
      "```용어풀이\n【암보장개시일 [예시]】\n(단, 15세 이상)계약일 90일\n```",
    );
  });

  it("문장이 안 끝났어도 【별표…】 아닌 【제목】 줄은 잇지 않고 박스로", () => {
    expect(body("[1] 계약일로 합니다.(이하「암보장개시일」이라 합니다)", "", "【암보장개시일[예시]】(단, 15세 이상)")).toBe(
      ["## 제1조(시험)", "", "@ 계약일로 합니다.(이하「암보장개시일」이라 합니다)", "", "```용어풀이", "【암보장개시일[예시]】", "(단, 15세 이상)", "```"].join("\n"),
    );
  });

  it("[제목] 줄 아래의 인용 줄은 그 제목의 박스", () => {
    expect(body("[2] 변경할 수 있습니다.", "", "[위험변경에 따른 계약변경 절차]", "", "> 통지", "", "> 변경 완료")).toContain(
      "```용어풀이\n【위험변경에 따른 계약변경 절차】\n통지 변경 완료\n```",
    );
  });

  it("항 번호 없는 조의 문단들은 단독 본문 하나로 잇는다", () => {
    expect(body("한가지형만을 적용합니다.", "", "[3년만기형]이 특약의 보험기간은 3년으로 합니다.")).toBe(
      ["## 제1조(시험)", "", "= 한가지형만을 적용합니다. [3년만기형]이 특약의 보험기간은 3년으로 합니다."].join("\n"),
    );
  });

  it("문장이 끝난 뒤 마커 없는 줄은 제목 없는 박스로 남긴다(본문을 잃지 않는다)", () => {
    expect(body("[1] 지급합니다.", "", "※ 위의 예시는 참고용입니다.")).toContain("```용어풀이\n※ 위의 예시는 참고용입니다.\n```");
  });

  it("원문 항 · 호 번호가 순서와 어긋나면 줄 끝에 원문번호를 남긴다", () => {
    expect(body("[1] 하나.", "", "[3] 셋.", "", "① 가", "", "③ 다")).toBe(
      ["## 제1조(시험)", "", "@ 하나.", "", "@ 셋. <!-- 원문번호: 3 -->", "", "  - 가", "", "  - 다 <!-- 원문번호: 3 -->"].join("\n"),
    );
  });

  it("마크다운 이스케이프(`1\\.`)를 푼다", () => {
    expect(body("본문 1\\. 입니다.")).toContain("= 본문 1. 입니다.");
  });
});

const SOURCE = `# 무배당 알파Plus보장보험2607 특별약관 — Ⅰ. 상해 관련 특별약관

> 원본: 무배당 알파Plus보장보험2607약관.pdf · PDF p.100–970 · 추출 2026-10-12 · build_terms_md.py (PyMuPDF)

<!-- p.120 -->

## 1. 일반상해사망보장 특별약관

### 제1조(보험금의 지급사유)

사망보험금을 지급합니다.

<!-- p.121 -->

## 2. 일반상해사망보장 추가특별약관

### 제1조(보험금의 지급사유)

[1] 지급합니다.

<!-- p.122 -->
[2] 둘째.

<!-- p.123 -->

## 3. 수술비(1-7종, 연간3회한)[상해]보장 특별약관
`;

describe("splitUnits · readSourceMeta · fixtureName", () => {
  it("`## N. 이름` 마다 특약 하나 — 쪽 범위는 쪽 주석에서", () => {
    const { units } = splitUnits(SOURCE);
    expect(units.map((u) => [u.no, u.title, u.startPage, u.endPage])).toEqual([
      [1, "일반상해사망보장 특별약관", 120, 120],
      [2, "일반상해사망보장 추가특별약관", 121, 122],
      [3, "수술비(1-7종, 연간3회한)[상해]보장 특별약관", 123, 123],
    ]);
  });

  it("`## N.` 이 없는 파일(보통약관)은 문서 하나", () => {
    const { units } = splitUnits("# 무배당 X 보통약관\n\n> 원본: X약관.pdf · 추출 2026-10-12\n\n<!-- p.100 -->\n\n## 제1관 목적\n\n### 제1조(목적)\n\n본문.\n\n<!-- p.101 -->\n\n### 제2조(정의)\n\n본문.\n");
    expect(units).toHaveLength(1);
    expect(units[0]).toMatchObject({ title: "무배당 X 보통약관", startPage: 100, endPage: 101 });
    expect(units[0].lines[0]).toBe("<!-- p.100 -->");
  });

  it("원본 줄에서 PDF 파일명 · 상품명 · 추출일", () => {
    expect(readSourceMeta(SOURCE)).toEqual({ pdf: "무배당 알파Plus보장보험2607약관.pdf", product: "무배당 알파Plus보장보험2607", extracted: "2026-10-12" });
  });

  it("파일명 — 「특별약관」을 떼고 빈칸은 `_` (2604 fixture 관례)", () => {
    expect(fixtureName("일반상해사망보장 특별약관")).toBe("일반상해사망보장");
    expect(fixtureName("일반상해사망보장 추가특별약관")).toBe("일반상해사망보장_추가");
    expect(fixtureName("수술비(1-7종, 연간3회한)[상해]보장 특별약관")).toBe("수술비(1-7종,_연간3회한)[상해]보장");
    expect(fixtureName("무배당 알파Plus보장보험2607 보통약관")).toBe("보통약관");
  });
});

describe("convertUnit — 파일 하나", () => {
  it("머리(제목 · 출처 · 상품) + 본문 + 통계, parseTerms 로 읽힌다", () => {
    const { units } = splitUnits(SOURCE);
    const meta = readSourceMeta(SOURCE);
    const out = convertUnit(units[1], { ...meta, kind: "특별약관" });
    expect(out).toBe(
      [
        "# 일반상해사망보장 추가특별약관",
        "",
        "> 출처: 무배당 알파Plus보장보험2607약관.pdf PDF 121–122쪽(인쇄 120–121쪽) · 추출일: 2026-10-12",
        "> 상품: 무배당 알파Plus보장보험2607 · 문서종류: 특별약관",
        "",
        "## 제1조(보험금의 지급사유)",
        "",
        "@ 지급합니다.",
        "",
        "@ 둘째.",
        "> 통계: 관 0 · 조 1 · 항 2 · 호 0 · 목 0 · 표 0",
        "",
      ].join("\n"),
    );
    const doc = parseTerms(out);
    expect(doc.title).toBe("일반상해사망보장 추가특별약관");
    expect(doc.sections[0].articles).toHaveLength(1);
  });

  it("한 쪽짜리는 쪽 범위 대신 한 쪽", () => {
    const { units } = splitUnits(SOURCE);
    expect(convertUnit(units[0], { ...readSourceMeta(SOURCE), kind: "특별약관" })).toContain("PDF 120쪽(인쇄 119쪽)");
  });
});
